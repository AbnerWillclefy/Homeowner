  for (const phone of document.querySelectorAll(".phone")) {
    phone.lang = "pt-BR";
    const walker = document.createTreeWalker(phone, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const text = node.textContent.trim();
      if (!text || /^[\d.]+$|^[A-Z]{2}$|@|^abnerwill|^jrocha$|^Abner$|^Ana$/.test(text)) continue;
      if (text in PT) node.textContent = node.textContent.replace(text, PT[text]);
      else missing.add(text);
    }
  }
